import katex from 'katex';
import { mml2omml } from 'mathml2omml';

/**
 * Office.js Word Service
 * Handles document manipulation and cursor insertions using Word JavaScript API
 */

export interface InsertionResult {
  success: boolean;
  message: string;
}

/**
 * Checks if Office.js is running inside a supported Word client
 */
export function isWordHost(): boolean {
  try {
    return (
      typeof Office !== 'undefined' &&
      typeof Word !== 'undefined' &&
      Boolean(Office.context) &&
      Boolean(Office.context.host) &&
      Boolean(Office.HostType) &&
      Office.context.host === Office.HostType.Word
    );
  } catch {
    return false;
  }
}

/**
 * Milestone 1 Required Function:
 * Inserts "Hello from Math Add-in" at the cursor using Word.run
 */
export async function insertHelloMath(): Promise<InsertionResult> {
  if (!isWordHost()) {
    return {
      success: false,
      message: 'Office.js chưa sẵn sàng hoặc không chạy trong Microsoft Word. Hãy sideload add-in vào Word.'
    };
  }

  try {
    await Word.run(async (context) => {
      const selection = context.document.getSelection();
      selection.insertText('Hello from Math Add-in', Word.InsertLocation.replace);
      await context.sync();
    });

    return {
      success: true,
      message: 'Đã chèn thành công "Hello from Math Add-in" tại vị trí con trỏ!'
    };
  } catch (error: any) {
    console.error('Lỗi khi gọi Word.run:', error);
    return {
      success: false,
      message: `Lỗi chèn văn bản: ${error?.message || error}`
    };
  }
}

/**
 * Normalizes mathematical operators like lim, max, min, inf, sup, sum, prod, bigcup, bigcap
 * so that limits/subscripts are placed directly below/above the operator (\limits),
 * matching standard Vietnamese educational typography (e.g. \lim\limits_{x \to 0}).
 */
export function normalizeMathLimits(code: string): string {
  if (!code) return '';
  return code.replace(
    /(?:\\|(?<=[^a-zA-Z]|^))(lim|max|min|inf|sup|limsup|liminf|sum|prod|bigcup|bigcap)(?!\s*\\limits)\s*([_\^])/g,
    (_, op, sub) => '\\' + op + '\\limits' + sub
  );
}

/**
 * Converts a LaTeX formula into clean MathML
 */
export function latexToMathML(latex: string): string {
  const normalized = normalizeMathLimits(latex);
  const rawMathML = katex.renderToString(normalized, {
    output: 'mathml',
    throwOnError: false
  });
  const cleanMathML = rawMathML
    .replace(/<annotation[^>]*>[\s\S]*?<\/annotation>/gi, '')
    .replace(/<annotation-xml[^>]*>[\s\S]*?<\/annotation-xml>/gi, '');
  const match = cleanMathML.match(/<math[\s\S]*?<\/math>/i);
  return match ? match[0] : rawMathML;
}

/**
 * Sanitizes OMML XML generated by mathml2omml:
 * Escapes unescaped '<', '>', '&' inside <m:t> text nodes so Word's XML parser never crashes.
 */
export function sanitizeOmml(omml: string): string {
  return omml.replace(/<m:t\b([^>]*)>([\s\S]*?)<\/m:t>/g, (_match, attrs, content) => {
    const safeAmp = content.replace(/&(?!(amp|lt|gt|quot|apos);)/g, '&amp;');
    const safeLtGt = safeAmp
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;');
    return `<m:t${attrs}>${safeLtGt}</m:t>`;
  });
}

/**
 * Converts a LaTeX formula into Word OMML (Office Math Markup Language)
 */
export function latexToOmml(latex: string): string {
  const mathml = latexToMathML(latex);
  const omml = mml2omml(mathml);
  return sanitizeOmml(omml);
}

/**
 * Wraps OMML into a complete flat OPC OpenXML package for Word insertOoxml
 */
export function buildOoxmlPackage(ommlXml: string, isInline = false): string {
  const mathContent = isInline ? ommlXml : `<m:oMathPara>${ommlXml}</m:oMathPara>`;

  return `<?xml version="1.0" standalone="yes"?>
<?mso-application progid="Word.Document"?>
<pkg:package xmlns:pkg="http://schemas.microsoft.com/office/2006/xmlPackage">
  <pkg:part pkg:name="/_rels/.rels" pkg:contentType="application/vnd.openxmlformats-package.relationships+xml" pkg:padding="512">
    <pkg:xmlData>
      <Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
        <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
      </Relationships>
    </pkg:xmlData>
  </pkg:part>
  <pkg:part pkg:name="/word/document.xml" pkg:contentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml">
    <pkg:xmlData>
      <w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" xmlns:m="http://schemas.openxmlformats.org/officeDocument/2006/math">
        <w:body>
          <w:p>
            ${mathContent}
          </w:p>
        </w:body>
      </w:document>
    </pkg:xmlData>
  </pkg:part>
</pkg:package>`;
}

/**
 * Inserts a native Word Equation from LaTeX using OMML OOXML
 * Directly injects native OMML Office Math into Word document.
 * Works on ALL desktop Word versions (Word 2013, 2016, 2019, 2021, Office 365).
 */
export async function insertMathEquation(latex: string, isInline = false): Promise<InsertionResult> {
  if (!isWordHost()) {
    return {
      success: false,
      message: 'Vui lòng mở Add-in trong Microsoft Word để chèn công thức vào văn bản.'
    };
  }

  try {
    const omml = latexToOmml(latex);
    const ooxmlPackage = buildOoxmlPackage(omml, isInline);

    await Word.run(async (context) => {
      const selection = context.document.getSelection();
      selection.insertOoxml(ooxmlPackage, Word.InsertLocation.replace);
      await context.sync();
    });

    return {
      success: true,
      message: isInline
        ? 'Đã chèn công thức chuẩn Word Equation (trong dòng) thành công!'
        : 'Đã chèn công thức chuẩn Word Equation (OMML) thành công!'
    };
  } catch (error: any) {
    console.error('Lỗi insertMathEquation (OOXML):', error);

    // Fallback: If OOXML fails, try inserting text
    try {
      await Word.run(async (context) => {
        const selection = context.document.getSelection();
        selection.insertText(latex, Word.InsertLocation.replace);
        await context.sync();
      });
      return {
        success: true,
        message: 'Đã chèn công thức dạng văn bản (LaTeX).'
      };
    } catch {
      return {
        success: false,
        message: `Lỗi chèn công thức: ${error?.message || error}`
      };
    }
  }
}

/**
 * Converts an SVG string into high-resolution PNG Base64 for native Word insertion
 * Renders at 2.5x - 3x scale (~300 DPI) for razor-sharp vector-like print quality
 */
export async function convertSvgToPngBase64(
  svgString: string,
  scale = 2.5
): Promise<{ base64: string; width: number; height: number }> {
  return new Promise((resolve, reject) => {
    try {
      let cleanSvg = svgString.trim();
      if (!cleanSvg.includes('xmlns="http://www.w3.org/2000/svg"')) {
        cleanSvg = cleanSvg.replace('<svg', '<svg xmlns="http://www.w3.org/2000/svg"');
      }

      // Check for XML syntax errors using DOMParser if available
      let xmlError = '';
      if (typeof DOMParser !== 'undefined') {
        try {
          const parser = new DOMParser();
          const doc = parser.parseFromString(cleanSvg, 'image/svg+xml');
          const errNode = doc.querySelector('parsererror');
          if (errNode) {
            xmlError = errNode.textContent || 'Lỗi cú pháp XML';
            console.error('[MathAddin] SVG XML syntax error:', xmlError);
          }
        } catch (pe) {
          console.warn('[MathAddin] DOMParser warning:', pe);
        }
      }

      // Extract original viewBox dimensions or width/height
      let w = 320;
      let h = 230;
      const vbMatch = cleanSvg.match(/viewBox=["']([0-9.\s-]+)["']/);
      if (vbMatch) {
        const parts = vbMatch[1].trim().split(/[\s,]+/);
        if (parts.length >= 4) {
          w = parseFloat(parts[2]) || 320;
          h = parseFloat(parts[3]) || 230;
        }
      } else {
        const wMatch = cleanSvg.match(/width=["']([0-9.]+)["']/);
        const hMatch = cleanSvg.match(/height=["']([0-9.]+)["']/);
        if (wMatch) w = parseFloat(wMatch[1]) || 320;
        if (hMatch) h = parseFloat(hMatch[1]) || 230;
      }

      // Ensure explicit width & height attributes for proper Image sizing
      if (!cleanSvg.includes('width=')) {
        cleanSvg = cleanSvg.replace('<svg', `<svg width="${w}"`);
      }
      if (!cleanSvg.includes('height=')) {
        cleanSvg = cleanSvg.replace('<svg', `<svg height="${h}"`);
      }

      const renderCanvas = (imgSource: HTMLImageElement) => {
        const canvas = document.createElement('canvas');
        canvas.width = Math.round(w * scale);
        canvas.height = Math.round(h * scale);
        const ctx = canvas.getContext('2d');
        if (!ctx) {
          throw new Error('Canvas 2D context not available');
        }

        // Fill crisp white background (preserves visibility in dark mode / print)
        ctx.fillStyle = '#ffffff';
        ctx.fillRect(0, 0, canvas.width, canvas.height);

        // High quality image smoothing
        ctx.imageSmoothingEnabled = true;
        ctx.imageSmoothingQuality = 'high';
        ctx.drawImage(imgSource, 0, 0, canvas.width, canvas.height);

        const dataUrl = canvas.toDataURL('image/png');
        const base64 = dataUrl.replace(/^data:image\/png;base64,/, '');
        return { base64, width: w, height: h };
      };

      // Try Blob URL approach first
      const blob = new Blob([cleanSvg], { type: 'image/svg+xml;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const img = new Image();

      img.onload = () => {
        try {
          const res = renderCanvas(img);
          URL.revokeObjectURL(url);
          resolve(res);
        } catch (err) {
          URL.revokeObjectURL(url);
          reject(err);
        }
      };

      img.onerror = () => {
        URL.revokeObjectURL(url);
        // Fallback: encode via Data URI
        try {
          // Use base64 data URI for better compatibility
          const utf8Bytes = encodeURIComponent(cleanSvg).replace(/%([0-9A-F]{2})/g, (_, p1) =>
            String.fromCharCode(parseInt(p1, 16))
          );
          const fallbackDataUrl = 'data:image/svg+xml;base64,' + btoa(utf8Bytes);
          const fallbackImg = new Image();
          fallbackImg.onload = () => {
            try {
              const res = renderCanvas(fallbackImg);
              resolve(res);
            } catch (err) {
              reject(err);
            }
          };
          fallbackImg.onerror = (e) => {
            const detail = xmlError ? ` (Cú pháp SVG: ${xmlError})` : '';
            reject(new Error(`Không thể vẽ SVG ra ảnh canvas: ${detail || e}`));
          };
          fallbackImg.src = fallbackDataUrl;
        } catch (fallbackErr) {
          reject(fallbackErr);
        }
      };

      img.src = url;
    } catch (e) {
      reject(e);
    }
  });
}

/**
 * Inserts vector geometry drawing as a high-resolution native Word picture at cursor
 */
export async function insertSvgAtCursor(svgContent: string, caption?: string): Promise<InsertionResult> {
  if (!isWordHost()) {
    return {
      success: false,
      message: 'Vui lòng mở Add-in trong Microsoft Word để chèn hình vẽ vào văn bản.'
    };
  }

  try {
    // 1. Convert SVG to high-resolution PNG Base64
    const { base64, width, height } = await convertSvgToPngBase64(svgContent, 2.5);

    // 2. Insert natively via Word JavaScript API (supported across all Word versions)
    await Word.run(async (context) => {
      const selection = context.document.getSelection();

      // Insert inline image
      const pic = selection.insertInlinePictureFromBase64(base64, Word.InsertLocation.replace);
      
      // Set display dimensions in points (preserves clear 1:1 scale)
      pic.width = width;
      pic.height = height;

      // Center the image paragraph
      pic.paragraph.alignment = Word.Alignment.centered;
      pic.paragraph.spaceBefore = 6;
      pic.paragraph.spaceAfter = 4;

      // Add centered caption paragraph below image if provided
      if (caption && caption.trim()) {
        const p = pic.paragraph.insertParagraph(caption.trim(), Word.InsertLocation.after);
        p.font.name = 'Times New Roman';
        p.font.size = 11;
        p.font.italic = true;
        p.font.color = '#333333';
        p.alignment = Word.Alignment.centered;
        p.spaceBefore = 2;
        p.spaceAfter = 12;
      }

      await context.sync();
    });

    return {
      success: true,
      message: `Đã chèn hình "${caption || 'Hình vẽ'}" vào Word thành công!`
    };
  } catch (error: any) {
    console.error('Lỗi insertSvgAtCursor:', error);
    return {
      success: false,
      message: `Lỗi chèn hình vẽ: ${error?.message || error}`
    };
  }
}

